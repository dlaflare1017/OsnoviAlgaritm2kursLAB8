        //   ┌──────────────────────┐
        //   │     Ввод A, N        │
        //   └─────────┬────────────┘
        //             │
        //             ▼
        //   ┌──────────────────────┐
        //   │   result = 1         │
        //   └─────────┬────────────┘
        //             │
        //             ▼
        //   ┌────────────────────────────┐
        //   │   если N > 0               │
        //   └─────────┬──────────────────┘
        //             │
        //   ┌─────────▼────────────┐
        //   │   i = 1              │
        //   └─────────┬────────────┘
        //             │
        //   ┌─────────▼────────────┐
        //   │ result = result * A  │
        //   │ i = i + 1            │
        //   └───────┬──────────────┘
        //           │
        //   ┌───────▼──────────────┐
        //   │ i ≤ N ?              │
        //   └───────┬──────────────┘
        //           │
        //      ┌────▼────┐
        //      │  Да     │
        //      └────┬────┘
        //           │
        //      ┌────▼────────────────────┐
        //      │  Вывести result         │
        //      └─────────────────────────┘

using System;

class Program
{
    static void Main()
    {
        Console.Write("Введите число A: ");
        double A = double.Parse(Console.ReadLine());

        Console.Write("Введите степень N (целое число): ");
        int N = int.Parse(Console.ReadLine());

        double result = 1;

        if (N > 0)
        {
            for (int i = 1; i <= N; i++)
            {
                result *= A;
            }
        }
        else if (N < 0)
        {
            for (int i = 1; i <= -N; i++)
            {
                result *= A;
            }
            result = 1 / result;
        }
        // если N == 0, результат останется равен 1

        Console.WriteLine($"Результат: {A}^{N} = {result}");
    }
}
